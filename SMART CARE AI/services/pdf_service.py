"""
PDF Processing Service for SmartCare AI.
Handles local text extraction using pypdf, file validation,
scanned document detection, and secure local file storage for medical reports.
"""

import os
import re
import time
from typing import Tuple
import pypdf

REPORTS_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "data", "reports")
MAX_FILE_SIZE_BYTES = 10 * 1024 * 1024  # 10 Megabytes


def validate_pdf_upload(uploaded_file) -> Tuple[bool, str]:
    """
    Validate that an uploaded file is a valid PDF under the 10 MB limit.
    Checks size, file extension, and PDF header signature.
    """
    if uploaded_file is None:
        return False, "No file was uploaded."

    file_size = getattr(uploaded_file, "size", 0)
    if file_size == 0:
        return False, "The uploaded file is empty (0 bytes). Please upload a valid clinical PDF report."

    # Validate file size
    if file_size > MAX_FILE_SIZE_BYTES:
        size_mb = file_size / (1024 * 1024)
        return False, f"File size exceeds the 10 MB limit ({size_mb:.2f} MB uploaded). Please upload a smaller PDF."

    # Validate extension
    filename = getattr(uploaded_file, "name", "").lower()
    if not filename.endswith(".pdf"):
        return False, "Invalid file format. Only PDF documents (.pdf) are supported."

    # Validate magic bytes (%PDF)
    try:
        uploaded_file.seek(0)
        header = uploaded_file.read(5)
        uploaded_file.seek(0)
        if not header.startswith(b"%PDF"):
            return False, "The uploaded file does not have a valid PDF document header."
    except Exception as e:
        return False, f"Could not read uploaded file: {str(e)}"

    return True, "File is valid."


def extract_text_from_pdf(uploaded_file) -> Tuple[bool, str, int]:
    """
    Extract text content from a PDF document locally using pypdf.
    Identifies scanned, password-protected, or image-only PDFs.

    Returns:
        (success: bool, extracted_text_or_error: str, page_count: int)
    """
    try:
        uploaded_file.seek(0)
        reader = pypdf.PdfReader(uploaded_file)

        # Check for password-protected or encrypted PDFs
        if getattr(reader, "is_encrypted", False):
            return (
                False,
                "⚠️ **This PDF document is password-protected or encrypted.**\n\n"
                "Please remove password protection from the document before uploading so text can be extracted locally.",
                0
            )

        page_count = len(reader.pages)

        if page_count == 0:
            return False, "The PDF file contains no pages.", 0

        extracted_text_pages = []
        for idx, page in enumerate(reader.pages):
            page_text = page.extract_text()
            if page_text and page_text.strip():
                extracted_text_pages.append(f"--- [Page {idx + 1}] ---\n{page_text.strip()}")

        full_extracted = "\n\n".join(extracted_text_pages).strip()

        # Check for scanned / image-only PDFs
        if len(full_extracted) < 30:
            return (
                False,
                "⚠️ **No extractable digital text found in this PDF.**\n\n"
                "This document appears to be a scanned image or photo of a paper report. "
                "The system processes digital PDFs with selectable text. Scanned photo documents require Optical Character Recognition (OCR), "
                "which is not currently active. Please upload a digital PDF report generated by your diagnostic lab.",
                page_count
            )

        return True, full_extracted, page_count

    except Exception as e:
        return False, f"Error processing PDF document: {str(e)}", 0


def save_pdf_to_storage(uploaded_file, patient_id: str) -> Tuple[bool, str, float]:
    """
    Save the uploaded PDF securely in the data/reports directory.

    Returns:
        (success: bool, file_path: str, file_size_kb: float)
    """
    os.makedirs(REPORTS_DIR, exist_ok=True)
    try:
        # Sanitize original file name
        original_name = uploaded_file.name
        safe_name = re.sub(r"[^a-zA-Z0-9_\-\.]", "_", original_name)
        timestamp = int(time.time())
        dest_filename = f"{patient_id}_{timestamp}_{safe_name}"
        dest_path = os.path.join(REPORTS_DIR, dest_filename)

        uploaded_file.seek(0)
        with open(dest_path, "wb") as f:
            f.write(uploaded_file.read())

        file_size_kb = round(os.path.getsize(dest_path) / 1024.0, 1)
        return True, dest_path, file_size_kb

    except Exception as e:
        return False, str(e), 0.0
